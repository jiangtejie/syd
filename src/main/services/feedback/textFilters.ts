/**
 * 文本级降噪（纯函数、零依赖，便于回归自检）。
 *
 * 为什么需要：规则路径的召回是以精确度为代价的，实测把一堆「业务往来通知」建成了客户议题：
 *   - `xin蓉：收到`                      → 被当成「客户留言未回复」
 *   - `成都 产地·鲜友：发票请查收`        → 被当成「咨询」
 *   - `订单专员：993537764 钟小飞 10件快运单号` → 被当成「物流」
 * 这些在采购/供应链群里尤其常见，会在看板上堆出永远无法「跟进」的假待办。
 *
 * 这里只做两类**高置信**过滤，宁可少滤也不误伤真实诉求：
 *   1) 纯应答/寒暄（收到、好的、谢谢…）—— 没有任何诉求信息；
 *   2) 事务性通知（请查收、已发货、开票资料、对账单、运单号…）—— 业务往来，不是客户问题；
 *      若同时带抱怨/追问信号（没/未/少/退/赔/怎么/多久…）则**不算**通知，照常提取。
 */

/** 去掉空白与常见标点，便于整句匹配 */
function normalize(text: string): string {
  return (text || '')
    .replace(/\s+/g, '')
    .replace(/[!！。.~～、,，?？:：;；"'“”‘’()（）[\]【】]/g, '')
}

/**
 * 纯应答/寒暄：整句（可叠加 1~3 个词）都是应答语，不含任何诉求信息。
 * 例：收到 / 好的 / 嗯嗯 / 谢谢老板 / 好的谢谢 / 辛苦了
 */
export function isAckOnly(text: string): boolean {
  const t = normalize(text)
  if (!t || t.length > 12) return false
  // 允许多个应答词叠加（好的谢谢），末尾可带称呼（谢谢老板/辛苦了哥）
  return /^(收到|好|好的|好滴|好嘞|行|可以|没问题|没事|嗯|哦|噢|ok|谢谢|多谢|感谢|辛苦|辛苦了|麻烦|麻烦了|是的|对的|对|没错|明白|了解|知道了){1,3}(老板|亲|哥|姐|总|老师|大大)?$/i.test(
    t
  )
}

/** 事务性通知的特征词：寄送/开票/对账/单号/查收 */
const NOTICE_RE =
  /(请查收|查收|已发货|已寄出|已开票|开票资料|发票已|回单|对账单|对账明细|发货明细|发货通知|收货确认|运单号|快递单号|物流单号|单号[:：]?\d{5,})/

/** 抱怨/追问信号：出现即认为不是单纯通知（可能是真实诉求，不能滤） */
const COMPLAINT_RE =
  /(没|未|错|少|缺|退|赔|投诉|不满|不对|问题|怎么|为什么|多久|什么时候|还没|催|急|漏|差)/

/**
 * 事务性通知：业务往来（发货单号、发票查收、对账明细…），不是客户问题。
 * 带抱怨/追问信号时返回 false —— 例如「快递单号 123 显示签收但没收到」是真诉求。
 */
export function isTransactionalNotice(text: string): boolean {
  const t = normalize(text)
  if (!t) return false
  if (COMPLAINT_RE.test(t)) return false
  return NOTICE_RE.test(t)
}

/** 规则/兜底路径共用的降噪判定：命中任一即不建议题 */
export function shouldSkipAsNoise(text: string): boolean {
  return isAckOnly(text) || isTransactionalNotice(text)
}
